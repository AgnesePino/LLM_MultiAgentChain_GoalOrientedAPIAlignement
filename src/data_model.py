class HighLevelGoalGenerationAction(str, Enum):
    ADD_NEW_HIGH_LEVEL_GOAL = "ADD_NEW_HIGH_LEVEL_GOAL"
    REPLACE_EXISTING_HIGH_LEVEL_GOAL = "REPLACE_EXISTING_HIGH_LEVEL_GOAL"


class HighLevelGoalGenerationSource(str, Enum):
    BRANCH_EVALUATION = "BRANCH_EVALUATION"
    DOCUMENTATION_COVERAGE = "DOCUMENTATION_COVERAGE"


class HighLevelGoalGeneratorInput(BaseModel):
    """
    Input forwarded to the existing top-down ``generate_high_level_goals``
    function.

    The field names intentionally match the original function parameters:
    ``project_description`` and ``actors``. No information about evaluation,
    correction, replacement, branch identifiers, or previous attempts is
    exposed to the generator.
    """

    project_description: str
    actors: Actors

    @model_validator(mode="after")
    def validate_generator_input(self) -> "HighLevelGoalGeneratorInput":
        if not self.project_description.strip():
            raise ValueError("project_description must be a non-empty string.")

        if not self.actors.actors:
            raise ValueError("actors must contain at least one actor.")

        return self


class HighLevelGoalGenerationRequest(BaseModel):
    """
    One validated request to generate HLGs through the original top-down block.

    ``generator_input`` is the only part forwarded to the HLG generator.
    ``action`` and ``target_branch_id`` are orchestration metadata and are never
    shown to the generator.
    """

    request_id: str
    action: HighLevelGoalGenerationAction
    source: HighLevelGoalGenerationSource
    generator_input: HighLevelGoalGeneratorInput = Field(
        description=(
            "The generation-request payload forwarded to the top-down HLG "
            "generator (project_description + actors)."
        )
    )

    target_branch_id: str | None = Field(
        default=None,
        description=(
            "Branch to replace for REPLACE_EXISTING_HIGH_LEVEL_GOAL; must "
            "be null for ADD_NEW_HIGH_LEVEL_GOAL."
        ),
    )
    origin_branch_id: str | None = Field(
        default=None,
        description=(
            "Branch that produced this request when source is "
            "BRANCH_EVALUATION; required in that case, otherwise unused."
        ),
    )
    generator_guidance: str | None = Field(
        default=None,
        description=(
            "Focused, actionable guidance produced by the bottom-up evaluator "
            "for the original HLG generator. It may explain what intention to "
            "capture or what scope error to correct, but it is not itself a "
            "final High-Level Goal."
        ),
    )
    rationale: str

    @model_validator(mode="after")
    def validate_generation_request(self) -> "HighLevelGoalGenerationRequest":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        if self.generator_guidance is not None and not self.generator_guidance.strip():
            raise ValueError(
                "generator_guidance must be null or a non-empty string."
            )

        if (
            self.action
            == HighLevelGoalGenerationAction.REPLACE_EXISTING_HIGH_LEVEL_GOAL
        ):
            if not self.target_branch_id:
                raise ValueError(
                    "REPLACE_EXISTING_HIGH_LEVEL_GOAL requires "
                    "target_branch_id."
                )
        elif self.target_branch_id is not None:
            raise ValueError(
                "target_branch_id must be null for ADD_NEW_HIGH_LEVEL_GOAL."
            )

        if (
            self.source == HighLevelGoalGenerationSource.BRANCH_EVALUATION
            and not self.origin_branch_id
        ):
            raise ValueError(
                "A BRANCH_EVALUATION request requires origin_branch_id."
            )

        return self


