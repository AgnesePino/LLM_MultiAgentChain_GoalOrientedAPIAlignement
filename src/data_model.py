from typing import Literal

from pydantic import BaseModel, Field, model_validator

"""
Structured data models used by the top-down and bottom-up goal pipeline.

The Global Goal Evaluator does not generate final high-level goals. When a
high-level goal must be added or replaced, it produces a generation request
whose ``generator_input`` contains exactly the information required by the
existing top-down HLG generator: a project description and a set of actors.

The orchestrator is responsible for:
- forwarding ``generator_input`` to the original top-down HLG generator;
- adding or replacing the generated goals according to ``action``;
- regenerating the corresponding low-level goals when required.
"""


class DocumentDescription(BaseModel):
    description: str


class Actor(BaseModel):
    name: str
    description: str


class Actors(BaseModel):
    actors: list[Actor]


class HighLevelGoal(BaseModel):
    name: str
    description: str
    actor: Actor


class HighLevelGoals(BaseModel):
    goals: list[HighLevelGoal]


class LowLevelGoal(BaseModel):
    name: str
    description: str
    high_level_associated: HighLevelGoal


class LowLevelGoals(BaseModel):
    low_level_goals: list[LowLevelGoal]


class API(BaseModel):
    api_name: str
    api_path: str
    description: str
    request_type: str


class APIMapping(BaseModel):
    APIs: list[API]
    low_level_goal: LowLevelGoal


class Critique(BaseModel):
    score: float
    comment: str


# ---------------------------------------------------------------------------
# Bottom-up High-Level Goal reconstruction
# ---------------------------------------------------------------------------


class BottomUpHighLevelGoalLLMOutput(BaseModel):
    """
    Semantic output requested from the bottom-up High-Level Goal Generator.

    Identifiers and traceability metadata are added deterministically by
    Python and are not generated by the LLM.
    """

    reconstructed_high_level_goal: str
    abstraction_rationale: str
    supporting_low_level_goal_ids: list[str]
    cohesion: Literal["high", "medium", "low"]
    confidence: Literal["high", "medium", "low"]


class BottomUpHighLevelGoal(BaseModel):
    """
    Final bottom-up reconstruction result for one branch.

    The original parent HLG is deliberately excluded. Parent traceability is
    maintained separately by the orchestrator.
    """

    branch_id: str
    reconstructed_high_level_goal: str
    abstraction_rationale: str
    supporting_low_level_goal_ids: list[str]
    source_low_level_goal_ids: list[str]
    cohesion: Literal["high", "medium", "low"]
    confidence: Literal["high", "medium", "low"]


# ---------------------------------------------------------------------------
# Requests for the existing top-down HLG generator
# ---------------------------------------------------------------------------


HighLevelGoalGenerationAction = Literal[
    "ADD_NEW_HIGH_LEVEL_GOAL",
    "REPLACE_EXISTING_HIGH_LEVEL_GOAL",
]

HighLevelGoalGenerationSource = Literal[
    "BRANCH_EVALUATION",
    "DOCUMENTATION_COVERAGE",
]


class HighLevelGoalGeneratorInput(BaseModel):
    """
    Input forwarded to the existing top-down ``generate_high_level_goals``
    function.

    The field names intentionally match the original function parameters:
    ``project_description`` and ``actors``. No information about evaluation,
    correction, replacement, branch identifiers, or previous attempts is
    exposed to the generator.
    """

    project_description: str
    actors: Actors

    @model_validator(mode="after")
    def validate_generator_input(self) -> "HighLevelGoalGeneratorInput":
        if not self.project_description.strip():
            raise ValueError("project_description must be a non-empty string.")

        if not self.actors.actors:
            raise ValueError("actors must contain at least one actor.")

        return self


class HighLevelGoalGenerationRequest(BaseModel):
    """
    One validated request to generate HLGs through the original top-down block.

    ``generator_input`` is the only part forwarded to the HLG generator.
    ``action`` and ``target_branch_id`` are orchestration metadata and are never
    shown to the generator.
    """

    request_id: str
    action: HighLevelGoalGenerationAction
    source: HighLevelGoalGenerationSource
    generator_input: HighLevelGoalGeneratorInput

    target_branch_id: str | None = None
    origin_branch_id: str | None = None
    rationale: str

    @model_validator(mode="after")
    def validate_generation_request(self) -> "HighLevelGoalGenerationRequest":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        if self.action == "REPLACE_EXISTING_HIGH_LEVEL_GOAL":
            if not self.target_branch_id:
                raise ValueError(
                    "REPLACE_EXISTING_HIGH_LEVEL_GOAL requires "
                    "target_branch_id."
                )
        elif self.target_branch_id is not None:
            raise ValueError(
                "target_branch_id must be null for ADD_NEW_HIGH_LEVEL_GOAL."
            )

        if self.source == "BRANCH_EVALUATION" and not self.origin_branch_id:
            raise ValueError(
                "A BRANCH_EVALUATION request requires origin_branch_id."
            )

        return self


# ---------------------------------------------------------------------------
# Global Goal Evaluator
# ---------------------------------------------------------------------------


GlobalGoalEvaluationDecision = Literal[
    "CONFIRM_BRANCH",
    "REGENERATE_LOW_LEVEL_GOALS",
    "MATCHES_OTHER_HIGH_LEVEL_GOAL",
    "ADD_NEW_HIGH_LEVEL_GOAL",
    "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL",
]


class GlobalGoalEvaluationLLMOutput(BaseModel):
    """
    Structured output requested from the Global Goal Evaluator LLM.

    The evaluator decides what must happen. For ADD/REWRITE decisions it
    provides a focused description of the documented intention that must be
    passed to the normal top-down HLG generator. It does not generate the final
    HLG name or description.
    """

    decision: GlobalGoalEvaluationDecision
    matched_high_level_goal_id: str | None = None
    generation_project_description: str | None = None
    rationale: str

    @model_validator(mode="after")
    def validate_decision_fields(self) -> "GlobalGoalEvaluationLLMOutput":
        if (
            self.decision != "MATCHES_OTHER_HIGH_LEVEL_GOAL"
            and self.matched_high_level_goal_id is not None
        ):
            raise ValueError(
                "matched_high_level_goal_id is valid only for "
                "MATCHES_OTHER_HIGH_LEVEL_GOAL."
            )

        requires_hlg_generation = self.decision in {
            "ADD_NEW_HIGH_LEVEL_GOAL",
            "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL",
        }

        if requires_hlg_generation:
            if (
                not self.generation_project_description
                or not self.generation_project_description.strip()
            ):
                raise ValueError(
                    f"{self.decision} requires a non-empty "
                    "generation_project_description."
                )
        elif self.generation_project_description is not None:
            raise ValueError(
                "generation_project_description must be null when the selected "
                "decision does not require HLG generation."
            )

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        return self


class GlobalGoalEvaluationResult(BaseModel):
    """
    Validated evaluator result for one branch.

    ``generation_request`` is present only when the original top-down HLG
    generator must add a new goal or generate a replacement. The evaluator
    never creates or applies a final ``HighLevelGoal`` object.
    """

    branch_id: str
    decision: GlobalGoalEvaluationDecision
    original_high_level_goal: HighLevelGoal
    reconstructed_high_level_goal: str | None = None
    matched_high_level_goal: HighLevelGoal | None = None
    generation_request: HighLevelGoalGenerationRequest | None = None
    rationale: str
    operational_action: str
    requires_high_level_regeneration: bool
    requires_low_level_regeneration: bool

    @model_validator(mode="after")
    def validate_generation_requirement(self) -> "GlobalGoalEvaluationResult":
        expected_high_level_regeneration = self.decision in {
            "ADD_NEW_HIGH_LEVEL_GOAL",
            "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL",
        }

        if (
            self.requires_high_level_regeneration
            != expected_high_level_regeneration
        ):
            raise ValueError(
                "requires_high_level_regeneration is inconsistent with decision."
            )

        if expected_high_level_regeneration and self.generation_request is None:
            raise ValueError(
                f"{self.decision} requires generation_request."
            )

        if (
            not expected_high_level_regeneration
            and self.generation_request is not None
        ):
            raise ValueError(
                "generation_request must be null when no HLG generation is "
                "required."
            )

        if self.decision == "MATCHES_OTHER_HIGH_LEVEL_GOAL":
            if self.matched_high_level_goal is None:
                raise ValueError(
                    "MATCHES_OTHER_HIGH_LEVEL_GOAL requires "
                    "matched_high_level_goal."
                )
        elif self.matched_high_level_goal is not None:
            raise ValueError(
                "matched_high_level_goal must be null for decisions other than "
                "MATCHES_OTHER_HIGH_LEVEL_GOAL."
            )

        return self


