class GlobalGoalEvaluationDecision(str, Enum):
    """Two-way decision used by the current branch-level feedback loop."""

    CONFIRM_BRANCH = "CONFIRM_BRANCH"
    REGENERATE_HIGH_LEVEL_GOAL = "REGENERATE_HIGH_LEVEL_GOAL"


class GlobalGoalEvaluationLLMOutput(BaseModel):
    """
    Structured output requested from the current Global Goal Evaluator.

    Branch evaluation is deliberately a single two-way gate. The evaluator
    receives the project documentation, the current HLG collection, the current
    branch id, and the HLG reconstructed bottom-up from that branch's LLGs. It
    does not inspect individual LLGs and does not classify the mismatch as an
    HLG problem versus an LLG problem.

    - ``CONFIRM_BRANCH`` keeps the branch unchanged.
    - ``REGENERATE_HIGH_LEVEL_GOAL`` rebuilds the branch from HLG level; the
      replacement HLG is then always decomposed into newly generated/evaluated
      LLGs before the next bottom-up iteration.
    """

    rationale: str
    decision: GlobalGoalEvaluationDecision = Field(
        description=(
            "The evaluator's local branch decision: CONFIRM_BRANCH or "
            "REGENERATE_HIGH_LEVEL_GOAL."
        )
    )
    matched_branch_id: str | None = Field(
        default=None,
        description=(
            "Legacy compatibility field. It must always be null in the "
            "current two-way branch evaluation."
        ),
    )
    generation_project_description: str | None = Field(
        default=None,
        description=(
            "Focused stakeholder-style project description forwarded to the "
            "original top-down HLG generator only when the decision is "
            "REGENERATE_HIGH_LEVEL_GOAL."
        ),
    )

    @model_validator(mode="after")
    def validate_decision_fields(self) -> "GlobalGoalEvaluationLLMOutput":
        if self.matched_branch_id is not None:
            raise ValueError(
                "matched_branch_id must always be null in the current "
                "two-way branch evaluation."
            )

        requires_hlg_generation = (
            self.decision
            == GlobalGoalEvaluationDecision.REGENERATE_HIGH_LEVEL_GOAL
        )

        if requires_hlg_generation:
            if (
                not self.generation_project_description
                or not self.generation_project_description.strip()
            ):
                raise ValueError(
                    "REGENERATE_HIGH_LEVEL_GOAL requires a non-empty "
                    "generation_project_description."
                )
        elif self.generation_project_description is not None:
            raise ValueError(
                "generation_project_description must be null for "
                "CONFIRM_BRANCH."
            )

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        return self


