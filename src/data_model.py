class GlobalGoalCycleResult(BaseModel):
    """
    Final trace/result of the single evolving HLG/LLG state.

    The cycle never ranks previous iterations and never rolls back to a
    previously observed goal set. ``final_*`` always contains the current
    HLG/LLG collection reached when execution stops. It is a validated final
    model only when ``converged`` is True; otherwise it is the latest snapshot
    retained for diagnostics and experimental traceability.

    ``best_validated_*`` remains in the schema only for compatibility with
    existing consumers and is always set to ``None`` by the current
    ``cycle_state._build_result`` implementation. ``last_candidate_*`` mirrors
    the current collection.
    """

    converged: bool
    stop_reason: GlobalGoalCycleStopReason
    completed_iterations: int
    max_iterations: int

    final_high_level_goals: HighLevelGoals
    final_low_level_goals: LowLevelGoals

    best_validated_high_level_goals: HighLevelGoals | None = Field(
        default=None,
        description=(
            "Legacy compatibility field. The current cycle has no best-state "
            "selection policy and sets this field to None."
        ),
    )
    best_validated_low_level_goals: LowLevelGoals | None = Field(
        default=None,
        description=(
            "Legacy compatibility field. The current cycle has no best-state "
            "selection policy and sets this field to None."
        ),
    )

    last_candidate_high_level_goals: HighLevelGoals = Field(
        description=(
            "The current HLG collection reached when execution stops; it "
            "mirrors final_high_level_goals in the current single-state policy."
        )
    )
    last_candidate_low_level_goals: LowLevelGoals = Field(
        description=(
            "The current LLG collection reached when execution stops; it "
            "mirrors final_low_level_goals in the current single-state policy."
        )
    )

    added_high_level_goals: list[HighLevelGoal] = Field(default_factory=list)
    iterations: list[GlobalGoalCycleIteration] = Field(default_factory=list)

    unresolved_bottom_up_errors: dict[str, str] = Field(default_factory=dict)
    unresolved_global_evaluation_errors: dict[str, str] = Field(
        default_factory=dict
    )
    unresolved_empty_branches: list[str] = Field(default_factory=list)
    unresolved_documentation_coverage_error: str | None = None
    unresolved_high_level_regeneration_error: str | None = None