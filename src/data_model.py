GlobalGoalCycleStopReason = Literal[
    "ALL_BRANCHES_CONFIRMED_AND_DOCUMENTATION_COVERED",
    "MAX_ITERATIONS_REACHED",
    "REPEATED_STATE_DETECTED",
    "BOTTOM_UP_RECONSTRUCTION_FAILED",
    "GLOBAL_EVALUATION_FAILED",
    "DOCUMENTATION_COVERAGE_EVALUATION_FAILED",
    "HIGH_LEVEL_REGENERATION_FAILED",
    "LOW_LEVEL_REGENERATION_FAILED",
]


class GlobalGoalCycleIteration(BaseModel):
    """Complete trace of one outer refinement-abstraction iteration."""

    iteration: int

    input_high_level_goals: HighLevelGoals
    input_low_level_goals: LowLevelGoals

    branch_traceability: dict[str, dict[str, object]] = Field(
        default_factory=dict
    )

    reconstructed_high_level_goals: dict[
        str,
        BottomUpHighLevelGoal,
    ] = Field(default_factory=dict)

    bottom_up_errors: dict[str, str] = Field(default_factory=dict)
    empty_branches: list[str] = Field(default_factory=list)

    global_evaluations: dict[
        str,
        GlobalGoalEvaluationResult,
    ] = Field(default_factory=dict)

    global_evaluation_errors: dict[str, str] = Field(default_factory=dict)

    high_level_generation_requests: list[
        HighLevelGoalGenerationRequest
    ] = Field(default_factory=list)
    generated_high_level_goals: HighLevelGoals | None = None
    high_level_regeneration_error: str | None = None

    documentation_coverage: DocumentationCoverageResult | None = None
    documentation_coverage_error: str | None = None
    documentation_fully_covered: bool = False

    newly_added_high_level_goals: list[HighLevelGoal] = Field(
        default_factory=list
    )

    updated_high_level_goals: HighLevelGoals | None = None
    regenerated_low_level_goals: LowLevelGoals | None = None

    all_branches_confirmed: bool = False
    requires_regeneration: bool = False

    state_signature: str


class GlobalGoalCycleResult(BaseModel):
    converged: bool
    stop_reason: GlobalGoalCycleStopReason
    completed_iterations: int
    max_iterations: int

    final_high_level_goals: HighLevelGoals
    final_low_level_goals: LowLevelGoals

    added_high_level_goals: list[HighLevelGoal] = Field(default_factory=list)
    iterations: list[GlobalGoalCycleIteration] = Field(default_factory=list)

    unresolved_bottom_up_errors: dict[str, str] = Field(default_factory=dict)
    unresolved_global_evaluation_errors: dict[str, str] = Field(
        default_factory=dict
    )
    unresolved_empty_branches: list[str] = Field(default_factory=list)
    unresolved_documentation_coverage_error: str | None = None
    unresolved_high_level_regeneration_error: str | None = None
