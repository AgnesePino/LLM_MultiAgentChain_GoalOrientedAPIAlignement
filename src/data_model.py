class HighLevelGoalDuplicateCandidateSource(str, Enum):
    """Origin of a candidate shown to the duplicate-selection evaluator."""

    GENERATED = "GENERATED"
    EXISTING = "EXISTING"


class HighLevelGoalRequestSelection(BaseModel):
    """
    Trace of request-level HLG admission before semantic duplicate resolution.

    Every focused request is verified even when the top-down generator returns
    only one candidate. At most one candidate may survive. When the verifier
    rejects all candidates, ``selected_candidate_id`` and ``selected_goal``
    are null and every supplied candidate is recorded in ``discarded_goals``.
    """

    request_id: str
    candidate_ids: list[str]
    selected_candidate_id: str | None = None
    selected_goal: HighLevelGoal | None = None
    discarded_goals: list[HighLevelGoal] = Field(default_factory=list)
    rationale: str

    @model_validator(mode="after")
    def validate_request_candidate_selection(
        self,
    ) -> "HighLevelGoalRequestSelection":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")
        if not self.candidate_ids:
            raise ValueError(
                "A request-level candidate selection requires at least one "
                "candidate id."
            )
        if len(set(self.candidate_ids)) != len(self.candidate_ids):
            raise ValueError("candidate_ids must be unique.")

        if self.selected_candidate_id is None:
            if self.selected_goal is not None:
                raise ValueError(
                    "selected_goal must be null when all candidates are rejected."
                )
            if len(self.discarded_goals) != len(self.candidate_ids):
                raise ValueError(
                    "When all candidates are rejected, discarded_goals must "
                    "contain every supplied candidate."
                )
        else:
            if self.selected_candidate_id not in self.candidate_ids:
                raise ValueError(
                    "selected_candidate_id must belong to candidate_ids."
                )
            if self.selected_goal is None:
                raise ValueError(
                    "selected_goal is required when a candidate is selected."
                )
            if len(self.discarded_goals) != len(self.candidate_ids) - 1:
                raise ValueError(
                    "discarded_goals must contain every non-selected candidate."
                )

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")
        return self

    @property
    def rejected_all(self) -> bool:
        """Whether request-level verification deliberately admitted no HLG."""
        return self.selected_candidate_id is None


class HighLevelGoalDuplicateResolution(BaseModel):
    """
    Trace of one evaluator-backed duplicate-resolution decision.

    A duplicate cluster may now contain both HLGs freshly returned by the
    top-down generator and HLGs that already belong to the current cycle
    state.  The evaluator still performs one operation only: choose the
    single candidate that best represents the documented intention and the
    GORE abstraction expected from an HLG.  Python then keeps that winner and
    removes every losing duplicate.

    ``candidate_sources`` records whether each candidate was GENERATED or
    EXISTING.  For existing candidates, ``candidate_branch_ids`` stores the
    current branch id so the update/orchestration layer can deterministically
    remove that branch when an improved generated candidate wins.  Generated
    candidates have a null branch id.
    """

    request_id: str
    candidate_ids: list[str]
    candidate_sources: dict[
        str, HighLevelGoalDuplicateCandidateSource
    ] = Field(default_factory=dict)
    candidate_branch_ids: dict[str, str | None] = Field(default_factory=dict)
    selected_candidate_id: str
    selected_goal: HighLevelGoal
    discarded_goals: list[HighLevelGoal] = Field(default_factory=list)
    rationale: str

    @model_validator(mode="after")
    def validate_duplicate_resolution(
        self,
    ) -> "HighLevelGoalDuplicateResolution":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")
        if len(self.candidate_ids) < 2:
            raise ValueError(
                "A duplicate resolution requires at least two candidate ids."
            )
        if len(set(self.candidate_ids)) != len(self.candidate_ids):
            raise ValueError("candidate_ids must be unique.")
        if self.selected_candidate_id not in self.candidate_ids:
            raise ValueError(
                "selected_candidate_id must belong to candidate_ids."
            )

        candidate_id_set = set(self.candidate_ids)
        if set(self.candidate_sources) != candidate_id_set:
            raise ValueError(
                "candidate_sources must contain exactly one entry for every "
                "candidate_id."
            )
        if set(self.candidate_branch_ids) != candidate_id_set:
            raise ValueError(
                "candidate_branch_ids must contain exactly one entry for "
                "every candidate_id."
            )

        for candidate_id in self.candidate_ids:
            source = self.candidate_sources[candidate_id]
            branch_id = self.candidate_branch_ids[candidate_id]
            if source == HighLevelGoalDuplicateCandidateSource.EXISTING:
                if not branch_id or not branch_id.strip():
                    raise ValueError(
                        "Every EXISTING duplicate candidate requires its "
                        "current branch id."
                    )
            elif branch_id is not None:
                raise ValueError(
                    "A GENERATED duplicate candidate must have a null "
                    "candidate_branch_id."
                )

        if len(self.discarded_goals) != len(self.candidate_ids) - 1:
            raise ValueError(
                "discarded_goals must contain every non-selected candidate."
            )
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")
        return self

    @property
    def selected_source(self) -> HighLevelGoalDuplicateCandidateSource:
        """Return the recorded origin of the selected candidate."""
        return self.candidate_sources[self.selected_candidate_id]

    @property
    def selected_existing_branch_id(self) -> str | None:
        """Return the selected branch id when the winner already existed."""
        return self.candidate_branch_ids[self.selected_candidate_id]

    @property
    def discarded_existing_branch_ids(self) -> list[str]:
        """Existing branches that lost against the selected candidate."""
        return [
            branch_id
            for candidate_id, branch_id in self.candidate_branch_ids.items()
            if candidate_id != self.selected_candidate_id
            and self.candidate_sources[candidate_id]
            == HighLevelGoalDuplicateCandidateSource.EXISTING
            and branch_id is not None
        ]


