"""
Central Pydantic data models for the whole pipeline.

This is the single source of truth for structured data used by both the
original top-down pipeline and the bottom-up feedback-loop extension.
Keeping all schemas here provides one explicit source of truth for model definitions.

The file is organized by pipeline responsibility:
1. shared/top-down core models;
2. bottom-up reconstruction outputs;
3. generation/regeneration requests;
4. duplicate-resolution traces;
5. Global Goal Evaluator outputs;
6. documentation-coverage outputs;
7. outer-cycle traces and results.
"""

from enum import Enum

from pydantic import BaseModel, Field, model_validator


