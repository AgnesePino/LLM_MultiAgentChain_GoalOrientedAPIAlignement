class LowLevelGoalRegenerationRequest(BaseModel):
    """
    Selective regeneration request used by the bottom-up feedback loop.

    ``high_level_goals`` contains only the HLGs whose decomposition must be
    regenerated. ``guidance_by_parent_name`` carries the Global Goal
    Evaluator's correction/scope suggestions for those HLGs. The callback
    handling this request must run the ORIGINAL LLG generator and its own
    evaluator/reflection loop before returning LowLevelGoals to the bottom-up
    cycle.
    """

    high_level_goals: HighLevelGoals
    guidance_by_parent_name: dict[str, str] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_regeneration_request(
        self,
    ) -> "LowLevelGoalRegenerationRequest":
        if not self.high_level_goals.goals:
            raise ValueError(
                "high_level_goals must contain at least one target HLG."
            )

        target_names = {goal.name for goal in self.high_level_goals.goals}
        unknown_names = set(self.guidance_by_parent_name) - target_names
        if unknown_names:
            raise ValueError(
                "guidance_by_parent_name contains goals that are not present "
                f"in high_level_goals: {sorted(unknown_names)}."
            )

        for parent_name, guidance in self.guidance_by_parent_name.items():
            if not parent_name.strip():
                raise ValueError(
                    "guidance_by_parent_name cannot contain an empty key."
                )
            if not guidance.strip():
                raise ValueError(
                    "guidance_by_parent_name values must be non-empty strings."
                )

        return self


