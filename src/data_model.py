class CohesionLevel(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class ConfidenceLevel(str, Enum):
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class BottomUpHighLevelGoalLLMOutput(BaseModel):
    """
    Semantic output requested from the bottom-up High-Level Goal Generator.

    Identifiers and traceability metadata are added deterministically by
    Python and are not generated by the LLM. ``supporting_low_level_goal_ids``
    here holds the branch-LOCAL ids exactly as returned by the LLM (e.g.
    'llg_001'), scoped only to the current prompt.
    """

    reconstructed_high_level_goal: str
    abstraction_rationale: str
    supporting_low_level_goal_ids: list[str] = Field(
        description=(
            "Branch-LOCAL low-level-goal ids selected by the LLM as "
            "evidence for the reconstructed goal (e.g. 'llg_001'), scoped "
            "only to the current prompt. Never full ids."
        )
    )
    cohesion: CohesionLevel
    confidence: ConfidenceLevel


class BottomUpHighLevelGoal(BottomUpHighLevelGoalLLMOutput):
    """
    Final bottom-up reconstruction result for one branch.

    Inherits ``reconstructed_high_level_goal``, ``abstraction_rationale``,
    ``cohesion``, and ``confidence`` unchanged from
    ``BottomUpHighLevelGoalLLMOutput``. ``supporting_low_level_goal_ids`` is
    also inherited by name, but here it holds the FULL ids
    (e.g. 'branch_001_llg_001'): the orchestrator deterministically derives
    them from the LLM's branch-local ids by prefixing each with
    ``branch_id``. The LLM itself never sees or produces full ids.

    The original parent HLG is deliberately excluded. Parent traceability is
    maintained separately by the orchestrator.
    """

    branch_id: str = Field(
        description=(
            "Opaque, deterministic branch identifier ('branch_001', ...) "
            "assigned by Python. Carries no semantic content from the "
            "original parent high-level goal."
        )
    )
    source_low_level_goal_ids: list[str] = Field(
        description=(
            "Full ids ('branch_001_llg_001', ...) of every low-level goal "
            "belonging to this branch, i.e. the complete evidence set given "
            "to the LLM."
        )
    )
    # Deterministically computed in Python as
    # source_low_level_goal_ids - supporting_low_level_goal_ids, preserving
    # the original order of source_low_level_goal_ids. Never produced by the
    # LLM: it is the complement of the ids the bottom-up reconstructor chose
    # as supporting evidence, kept explicit for traceability and experimental
    # analysis. The current Global Goal Evaluator receives only HLG', not the
    # individual LLG evidence lists.
    non_supporting_low_level_goal_ids: list[str] = Field(
        description=(
            "Full ids present in source_low_level_goal_ids but NOT in "
            "supporting_low_level_goal_ids, in source order. Computed "
            "deterministically in Python (never by the LLM) as the "
            "complement of the reconstructor's supporting-evidence "
            "selection; retained for traceability and experimental analysis."
        )
    )


