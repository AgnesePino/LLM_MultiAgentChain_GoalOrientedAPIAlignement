class DocumentationCoverageStatus(str, Enum):
    COMPLETE = "COMPLETE"
    MISSING_HIGH_LEVEL_GOALS = "MISSING_HIGH_LEVEL_GOALS"


class MissingHighLevelGoalProposal(BaseModel):
    """
    One autonomous documented intention missing from the current HLG set.

    ``project_description`` is a focused description to be used as normal input
    by the top-down HLG generator. It is not the final HLG formulation.
    """

    project_description: str
    actor: Actor
    source_evidence: str
    rationale: str

    @model_validator(mode="after")
    def validate_missing_goal_proposal(self) -> "MissingHighLevelGoalProposal":
        if not self.project_description.strip():
            raise ValueError("project_description must be a non-empty string.")

        if not self.source_evidence.strip():
            raise ValueError("source_evidence must be a non-empty string.")

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        return self


class DocumentationCoverageLLMOutput(BaseModel):
    """Structured output of the global documentation-coverage evaluator."""

    status: DocumentationCoverageStatus
    missing_high_level_goals: list[MissingHighLevelGoalProposal] = Field(
        default_factory=list
    )
    observations: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_status_and_missing_goals(
        self,
    ) -> "DocumentationCoverageLLMOutput":
        if (
            self.status == DocumentationCoverageStatus.COMPLETE
            and self.missing_high_level_goals
        ):
            raise ValueError(
                "Status COMPLETE cannot contain missing high-level goals."
            )

        if (
            self.status == DocumentationCoverageStatus.MISSING_HIGH_LEVEL_GOALS
            and not self.missing_high_level_goals
        ):
            raise ValueError(
                "Status MISSING_HIGH_LEVEL_GOALS requires at least one "
                "missing high-level goal."
            )

        return self


class DocumentationCoverageResult(BaseModel):
    """
    Validated coverage result.

    Missing intentions are converted into generation requests. No final HLG is
    directly generated or added by the documentation-coverage evaluator.
    """

    status: DocumentationCoverageStatus
    missing_high_level_goals: list[MissingHighLevelGoalProposal] = Field(
        default_factory=list
    )
    generation_requests: list[HighLevelGoalGenerationRequest] = Field(
        default_factory=list
    )
    observations: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_generation_requests(self) -> "DocumentationCoverageResult":
        if (
            self.status == DocumentationCoverageStatus.COMPLETE
            and self.generation_requests
        ):
            raise ValueError(
                "Status COMPLETE cannot contain generation requests."
            )

        if (
            self.status == DocumentationCoverageStatus.MISSING_HIGH_LEVEL_GOALS
            and not self.generation_requests
        ):
            raise ValueError(
                "Missing documented HLGs require generation requests."
            )

        return self


