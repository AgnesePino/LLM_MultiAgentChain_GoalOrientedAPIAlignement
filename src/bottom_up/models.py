class GlobalGoalEvaluationDecision(str, Enum):
    CONFIRM_BRANCH = "CONFIRM_BRANCH"
    REGENERATE_LOW_LEVEL_GOALS = "REGENERATE_LOW_LEVEL_GOALS"
    MATCHES_OTHER_HIGH_LEVEL_GOAL = "MATCHES_OTHER_HIGH_LEVEL_GOAL"
    ADD_NEW_HIGH_LEVEL_GOAL = "ADD_NEW_HIGH_LEVEL_GOAL"
    REWRITE_ORIGINAL_HIGH_LEVEL_GOAL = "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL"


class GlobalGoalEvaluationLLMOutput(BaseModel):
    """
    Structured output requested from the Global Goal Evaluator LLM.

    The evaluator decides what must happen. For ADD/REWRITE decisions it
    provides a focused description of the documented intention that must be
    passed to the normal top-down HLG generator. It does not generate the final
    HLG name or description.

    Superseded, for the non-empty-branch path, by the three-stage sequence
    (``BranchConsistencyLLMOutput`` -> ``OtherGoalMatchLLMOutput`` ->
    ``GoalDiscoveryLLMOutput``). Kept because ``evaluate_empty_branch`` still
    uses it for its single-stage evaluation.
    """

    rationale: str
    decision: GlobalGoalEvaluationDecision = Field(
        description=(
            "The evaluator's single structural decision for this branch "
            "(CONFIRM_BRANCH, REGENERATE_LOW_LEVEL_GOALS, "
            "MATCHES_OTHER_HIGH_LEVEL_GOAL, ADD_NEW_HIGH_LEVEL_GOAL, or "
            "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL)."
        )
    )
    matched_branch_id: str | None = Field(
        default=None,
        description=(
            "Opaque branch id of the matched high-level goal (e.g. "
            "'branch_005'), never the goal's own name/label. Valid only "
            "for MATCHES_OTHER_HIGH_LEVEL_GOAL."
        ),
    )
    generation_project_description: str | None = Field(
        default=None,
        description=(
            "Ordinary stakeholder-style project description forwarded "
            "as-is to the top-down HLG generator; non-null only for "
            "ADD_NEW_HIGH_LEVEL_GOAL / REWRITE_ORIGINAL_HIGH_LEVEL_GOAL."
        ),
    )

    @model_validator(mode="after")
    def validate_decision_fields(self) -> "GlobalGoalEvaluationLLMOutput":
        if (
            self.decision
            != GlobalGoalEvaluationDecision.MATCHES_OTHER_HIGH_LEVEL_GOAL
            and self.matched_branch_id is not None
        ):
            raise ValueError(
                "matched_branch_id is valid only for "
                "MATCHES_OTHER_HIGH_LEVEL_GOAL."
            )

        requires_hlg_generation = self.decision in {
            GlobalGoalEvaluationDecision.ADD_NEW_HIGH_LEVEL_GOAL,
            GlobalGoalEvaluationDecision.REWRITE_ORIGINAL_HIGH_LEVEL_GOAL,
        }

        if requires_hlg_generation:
            if (
                not self.generation_project_description
                or not self.generation_project_description.strip()
            ):
                raise ValueError(
                    f"{self.decision} requires a non-empty "
                    "generation_project_description."
                )
        elif self.generation_project_description is not None:
            raise ValueError(
                "generation_project_description must be null when the selected "
                "decision does not require HLG generation."
            )

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        return self


