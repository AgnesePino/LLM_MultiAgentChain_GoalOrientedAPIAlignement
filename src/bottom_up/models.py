class GlobalGoalCycleStopReason(str, Enum):
    ALL_BRANCHES_CONFIRMED_AND_DOCUMENTATION_COVERED = (
        "ALL_BRANCHES_CONFIRMED_AND_DOCUMENTATION_COVERED"
    )
    MAX_ITERATIONS_REACHED = "MAX_ITERATIONS_REACHED"
    REPEATED_STATE_DETECTED = "REPEATED_STATE_DETECTED"
    SEMANTIC_REPEATED_STATE_DETECTED = "SEMANTIC_REPEATED_STATE_DETECTED"
    BOTTOM_UP_RECONSTRUCTION_FAILED = "BOTTOM_UP_RECONSTRUCTION_FAILED"
    GLOBAL_EVALUATION_FAILED = "GLOBAL_EVALUATION_FAILED"
