class GlobalGoalCycleResult(BaseModel):
    """
    ``final_*`` follows an explicit policy, kept for compatibility with
    existing consumers:
    - if ``converged`` is True, ``final_*`` is the converged, validated
      current state;
    - otherwise, ``final_*`` is ``best_validated_*`` when one exists, and
      falls back to ``last_candidate_*`` only when no state ever completed
      bottom-up reconstruction and global branch evaluation without errors.

    ``best_validated_*`` and ``last_candidate_*`` are kept separately so no
    experimental information is lost:
    - ``best_validated_*``: the best state (by
      ``_compute_validated_state_quality``) that completed bottom-up
      reconstruction and global branch evaluation with no structural errors;
      ``None`` if no such state was ever produced.
    - ``last_candidate_*``: the last HLG/LLG state reached by the pipeline,
      whether or not it has itself completed a further validation pass (it
      may be a state that was just (re)generated and never evaluated).
    """

    converged: bool
    stop_reason: GlobalGoalCycleStopReason
    completed_iterations: int
    max_iterations: int

    final_high_level_goals: HighLevelGoals
    final_low_level_goals: LowLevelGoals

    best_validated_high_level_goals: HighLevelGoals | None = Field(
        default=None,
        description=(
            "The best state (by _compute_validated_state_quality) that "
            "completed bottom-up reconstruction and global branch "
            "evaluation with no structural errors; None if no such state "
            "was ever produced."
        ),
    )
    best_validated_low_level_goals: LowLevelGoals | None = Field(
        default=None,
        description=(
            "Low-level-goal counterpart of best_validated_high_level_goals, "
            "always set together with it."
        ),
    )

    last_candidate_high_level_goals: HighLevelGoals = Field(
        description=(
            "The last HLG state reached by the pipeline, whether or not it "
            "has itself completed a further validation pass (it may be a "
            "state that was just (re)generated and never evaluated)."
        )
    )
    last_candidate_low_level_goals: LowLevelGoals = Field(
        description=(
            "Low-level-goal counterpart of last_candidate_high_level_goals."
        )
    )

    added_high_level_goals: list[HighLevelGoal] = Field(default_factory=list)
    iterations: list[GlobalGoalCycleIteration] = Field(default_factory=list)

    unresolved_bottom_up_errors: dict[str, str] = Field(default_factory=dict)
    unresolved_global_evaluation_errors: dict[str, str] = Field(
        default_factory=dict
    )
    unresolved_empty_branches: list[str] = Field(default_factory=list)
    unresolved_documentation_coverage_error: str | None = None
    unresolved_high_level_regeneration_error: str | None = None
