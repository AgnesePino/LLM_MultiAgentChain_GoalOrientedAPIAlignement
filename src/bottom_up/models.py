class HighLevelGoalGenerationAction(str, Enum):
    ADD_NEW_HIGH_LEVEL_GOAL = "ADD_NEW_HIGH_LEVEL_GOAL"
    REPLACE_EXISTING_HIGH_LEVEL_GOAL = "REPLACE_EXISTING_HIGH_LEVEL_GOAL"


class HighLevelGoalGenerationSource(str, Enum):
    BRANCH_EVALUATION = "BRANCH_EVALUATION"
    DOCUMENTATION_COVERAGE = "DOCUMENTATION_COVERAGE"


class HighLevelGoalGeneratorInput(BaseModel):
    """
    Input forwarded to the existing top-down ``generate_high_level_goals``
    function.

    The field names intentionally match the original function parameters:
    ``project_description`` and ``actors``. No information about evaluation,
    correction, replacement, branch identifiers, or previous attempts is
    exposed to the generator.
    """

    project_description: str
    actors: Actors

    @model_validator(mode="after")
    def validate_generator_input(self) -> "HighLevelGoalGeneratorInput":
        if not self.project_description.strip():
            raise ValueError("project_description must be a non-empty string.")

        if not self.actors.actors:
            raise ValueError("actors must contain at least one actor.")

        return self


class HighLevelGoalGenerationRequest(BaseModel):
    """
    One validated request to generate HLGs through the original top-down block.

    ``generator_input`` is the only part forwarded to the HLG generator.
    ``action`` and ``target_branch_id`` are orchestration metadata and are never
    shown to the generator.
    """

    request_id: str
    action: HighLevelGoalGenerationAction
    source: HighLevelGoalGenerationSource
    generator_input: HighLevelGoalGeneratorInput = Field(
        description=(
            "The generation-request payload forwarded to the top-down HLG "
            "generator (project_description + actors)."
        )
    )

    target_branch_id: str | None = Field(
        default=None,
        description=(
            "Branch to replace for REPLACE_EXISTING_HIGH_LEVEL_GOAL; must "
            "be null for ADD_NEW_HIGH_LEVEL_GOAL."
        ),
    )
    origin_branch_id: str | None = Field(
        default=None,
        description=(
            "Branch that produced this request when source is "
            "BRANCH_EVALUATION; required in that case, otherwise unused."
        ),
    )
    rationale: str

    @model_validator(mode="after")
    def validate_generation_request(self) -> "HighLevelGoalGenerationRequest":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")

        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        if (
            self.action
            == HighLevelGoalGenerationAction.REPLACE_EXISTING_HIGH_LEVEL_GOAL
        ):
            if not self.target_branch_id:
                raise ValueError(
                    "REPLACE_EXISTING_HIGH_LEVEL_GOAL requires "
                    "target_branch_id."
                )
        elif self.target_branch_id is not None:
            raise ValueError(
                "target_branch_id must be null for ADD_NEW_HIGH_LEVEL_GOAL."
            )

        if (
            self.source == HighLevelGoalGenerationSource.BRANCH_EVALUATION
            and not self.origin_branch_id
        ):
            raise ValueError(
                "A BRANCH_EVALUATION request requires origin_branch_id."
            )

        return self


# ---------------------------------------------------------------------------
# Selection among semantically duplicate HLG candidates
# ---------------------------------------------------------------------------


class HighLevelGoalDuplicateCandidateSource(str, Enum):
    """Origin of a candidate shown to the duplicate-selection evaluator."""

    GENERATED = "GENERATED"
    EXISTING = "EXISTING"


class HighLevelGoalDuplicateSelectionLLMOutput(BaseModel):
    """
    Structured output of the evaluator stage that resolves one cluster of
    semantically duplicate HLG candidates. A cluster may contain newly
    generated candidates, already-existing HLGs, or both.

    The evaluator is allowed to select one candidate only. It never rewrites
    a candidate and never creates a new HighLevelGoal.
    """

    selected_candidate_id: str = Field(
        description=(
            "Identifier of the candidate to keep. It must be one of the "
            "candidate ids supplied in the duplicate-selection prompt."
        )
    )
    rationale: str

    @model_validator(mode="after")
    def validate_duplicate_selection(
        self,
    ) -> "HighLevelGoalDuplicateSelectionLLMOutput":
        if not self.selected_candidate_id.strip():
            raise ValueError(
                "selected_candidate_id must be a non-empty string."
            )
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")
        return self


class HighLevelGoalDuplicateResolution(BaseModel):
    """
    Trace of one evaluator-backed duplicate-resolution decision.

    A duplicate cluster may now contain both HLGs freshly returned by the
    top-down generator and HLGs that already belong to the current cycle
    state.  The evaluator still performs one operation only: choose the
    single candidate that best represents the documented intention and the
    GORE abstraction expected from an HLG.  Python then keeps that winner and
    removes every losing duplicate.

    ``candidate_sources`` records whether each candidate was GENERATED or
    EXISTING.  For existing candidates, ``candidate_branch_ids`` stores the
    current branch id so the update/orchestration layer can deterministically
    remove that branch when an improved generated candidate wins.  Generated
    candidates have a null branch id.
    """

    request_id: str
    candidate_ids: list[str]
    candidate_sources: dict[
        str, HighLevelGoalDuplicateCandidateSource
    ] = Field(default_factory=dict)
    candidate_branch_ids: dict[str, str | None] = Field(default_factory=dict)
    selected_candidate_id: str
    selected_goal: HighLevelGoal
    discarded_goals: list[HighLevelGoal] = Field(default_factory=list)
    rationale: str

    @model_validator(mode="after")
    def validate_duplicate_resolution(
        self,
    ) -> "HighLevelGoalDuplicateResolution":
        if not self.request_id.strip():
            raise ValueError("request_id must be a non-empty string.")
        if len(self.candidate_ids) < 2:
            raise ValueError(
                "A duplicate resolution requires at least two candidate ids."
            )
        if len(set(self.candidate_ids)) != len(self.candidate_ids):
            raise ValueError("candidate_ids must be unique.")
        if self.selected_candidate_id not in self.candidate_ids:
            raise ValueError(
                "selected_candidate_id must belong to candidate_ids."
            )

        candidate_id_set = set(self.candidate_ids)
        if set(self.candidate_sources) != candidate_id_set:
            raise ValueError(
                "candidate_sources must contain exactly one entry for every "
                "candidate_id."
            )
        if set(self.candidate_branch_ids) != candidate_id_set:
            raise ValueError(
                "candidate_branch_ids must contain exactly one entry for "
                "every candidate_id."
            )

        for candidate_id in self.candidate_ids:
            source = self.candidate_sources[candidate_id]
            branch_id = self.candidate_branch_ids[candidate_id]
            if source == HighLevelGoalDuplicateCandidateSource.EXISTING:
                if not branch_id or not branch_id.strip():
                    raise ValueError(
                        "Every EXISTING duplicate candidate requires its "
                        "current branch id."
                    )
            elif branch_id is not None:
                raise ValueError(
                    "A GENERATED duplicate candidate must have a null "
                    "candidate_branch_id."
                )

        if len(self.discarded_goals) != len(self.candidate_ids) - 1:
            raise ValueError(
                "discarded_goals must contain every non-selected candidate."
            )
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")
        return self

    @property
    def selected_source(self) -> HighLevelGoalDuplicateCandidateSource:
        """Return the recorded origin of the selected candidate."""
        return self.candidate_sources[self.selected_candidate_id]

    @property
    def selected_existing_branch_id(self) -> str | None:
        """Return the selected branch id when the winner already existed."""
        return self.candidate_branch_ids[self.selected_candidate_id]

    @property
    def discarded_existing_branch_ids(self) -> list[str]:
        """Existing branches that lost against the selected candidate."""
        return [
            branch_id
            for candidate_id, branch_id in self.candidate_branch_ids.items()
            if candidate_id != self.selected_candidate_id
            and self.candidate_sources[candidate_id]
            == HighLevelGoalDuplicateCandidateSource.EXISTING
            and branch_id is not None
        ]


