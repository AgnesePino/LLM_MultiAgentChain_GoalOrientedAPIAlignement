class BranchConsistencyLLMOutput(BaseModel):
    """
    Stage 1 output: does the current low-level decomposition reconstruct its
    own parent high-level goal correctly?

    Answers only the parent/candidate/decomposition-consistency question. It
    must never compare the candidate with other high-level goals and must
    never decide MATCHES_OTHER_HIGH_LEVEL_GOAL, ADD_NEW_HIGH_LEVEL_GOAL, or
    REWRITE_ORIGINAL_HIGH_LEVEL_GOAL.
    """

    rationale: str
    parent_supported: bool
    candidate_supported: bool
    preserves_parent_intention: bool
    decomposition_complete: bool

    @model_validator(mode="after")
    def validate_rationale(self) -> "BranchConsistencyLLMOutput":
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")
        return self

    @property
    def confirms_branch(self) -> bool:
        return (
            self.parent_supported
            and self.candidate_supported
            and self.preserves_parent_intention
            and self.decomposition_complete
        )


class OtherGoalMatchLLMOutput(BaseModel):
    """
    Stage 2 output: does the candidate correspond to another already-extracted
    high-level goal of the project?

    Only evaluated when Stage 1 did not confirm the branch. Must never decide
    whether to add or rewrite a high-level goal.

    ``matched_branch_id`` (not ``matched_high_level_goal_id``) on purpose: the
    value the model must return is the opaque branch identifier shown to it
    (e.g. ``branch_005``), never the HLG's own name/label, which is a
    different string the model could otherwise confuse it with.
    """

    rationale: str
    matches_other_high_level_goal: bool
    matched_branch_id: str | None = None

    @model_validator(mode="after")
    def validate_match_fields(self) -> "OtherGoalMatchLLMOutput":
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        if self.matches_other_high_level_goal:
            if not self.matched_branch_id:
                raise ValueError(
                    "matches_other_high_level_goal=True requires a non-null "
                    "matched_branch_id."
                )
        elif self.matched_branch_id is not None:
            raise ValueError(
                "matched_branch_id must be null when "
                "matches_other_high_level_goal is False."
            )

        return self


class GoalDiscoveryOutcome(str, Enum):
    REGENERATE_LOW_LEVEL_GOALS = "REGENERATE_LOW_LEVEL_GOALS"
    ADD_NEW_HIGH_LEVEL_GOAL = "ADD_NEW_HIGH_LEVEL_GOAL"
    REWRITE_ORIGINAL_HIGH_LEVEL_GOAL = "REWRITE_ORIGINAL_HIGH_LEVEL_GOAL"


class GoalDiscoveryLLMOutput(BaseModel):
    """
    Stage 3 output: given that the candidate does not correctly reconstruct
    its own parent and does not correspond to another already-extracted
    high-level goal, what does the evidence indicate?

    Only evaluated when Stage 1 did not confirm the branch and Stage 2 found
    no match with another high-level goal.
    """

    rationale: str
    outcome: GoalDiscoveryOutcome
    generation_project_description: str | None = Field(
        default=None,
        description=(
            "Ordinary stakeholder-style project description forwarded "
            "as-is to the top-down HLG generator; non-null only for "
            "ADD_NEW_HIGH_LEVEL_GOAL / REWRITE_ORIGINAL_HIGH_LEVEL_GOAL."
        ),
    )

    @model_validator(mode="after")
    def validate_outcome_fields(self) -> "GoalDiscoveryLLMOutput":
        if not self.rationale.strip():
            raise ValueError("rationale must be a non-empty string.")

        requires_hlg_generation = self.outcome in {
            GoalDiscoveryOutcome.ADD_NEW_HIGH_LEVEL_GOAL,
            GoalDiscoveryOutcome.REWRITE_ORIGINAL_HIGH_LEVEL_GOAL,
        }

        if requires_hlg_generation:
            if (
                not self.generation_project_description
                or not self.generation_project_description.strip()
            ):
                raise ValueError(
                    f"{self.outcome} requires a non-empty "
                    "generation_project_description."
                )
        elif self.generation_project_description is not None:
            raise ValueError(
                "generation_project_description must be null for "
                "REGENERATE_LOW_LEVEL_GOALS."
            )

        return self


class GlobalGoalEvaluationResult(BaseModel):
    """
    Validated evaluator result for one branch.

    ``generation_request`` is present only when the original top-down HLG
    generator must add a new goal or generate a replacement. The evaluator
    never creates or applies a final ``HighLevelGoal`` object.
    """

    branch_id: str
    decision: GlobalGoalEvaluationDecision
    original_high_level_goal: HighLevelGoal
    reconstructed_high_level_goal: str | None = None
    matched_high_level_goal: HighLevelGoal | None = None
    generation_request: HighLevelGoalGenerationRequest | None = None
    rationale: str
    operational_action: str = Field(
        description=(
            "Human-readable operational label mirroring ``decision`` "
            "(e.g. 'KEEP_PARENT'), used for logging/traceability only."
        )
    )
    requires_high_level_regeneration: bool
    requires_low_level_regeneration: bool

    @model_validator(mode="after")
    def validate_generation_requirement(self) -> "GlobalGoalEvaluationResult":
        expected_high_level_regeneration = self.decision in {
            GlobalGoalEvaluationDecision.ADD_NEW_HIGH_LEVEL_GOAL,
            GlobalGoalEvaluationDecision.REWRITE_ORIGINAL_HIGH_LEVEL_GOAL,
        }

        if (
            self.requires_high_level_regeneration
            != expected_high_level_regeneration
        ):
            raise ValueError(
                "requires_high_level_regeneration is inconsistent with decision."
            )

        if expected_high_level_regeneration and self.generation_request is None:
            raise ValueError(
                f"{self.decision} requires generation_request."
            )

        if (
            not expected_high_level_regeneration
            and self.generation_request is not None
        ):
            raise ValueError(
                "generation_request must be null when no HLG generation is "
                "required."
            )

        if (
            self.decision
            == GlobalGoalEvaluationDecision.MATCHES_OTHER_HIGH_LEVEL_GOAL
        ):
            if self.matched_high_level_goal is None:
                raise ValueError(
                    "MATCHES_OTHER_HIGH_LEVEL_GOAL requires "
                    "matched_high_level_goal."
                )
        elif self.matched_high_level_goal is not None:
            raise ValueError(
                "matched_high_level_goal must be null for decisions other than "
                "MATCHES_OTHER_HIGH_LEVEL_GOAL."
            )

        return self


