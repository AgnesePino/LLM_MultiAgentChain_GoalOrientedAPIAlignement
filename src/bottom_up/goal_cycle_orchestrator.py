"""
Deterministic orchestration of the bottom-up HLG-regeneration feedback loop.

The cycle starts from HLGs and LLGs already generated by the original top-down
pipeline. At each iteration it reconstructs one HLG' from each branch's current
LLGs and asks the Global Goal Evaluator for exactly one of two local decisions:

- CONFIRM_BRANCH: preserve the complete branch unchanged;
- REGENERATE_HIGH_LEVEL_GOAL: invoke the ORIGINAL HLG Generator -> HLG
  Evaluator loop to replace that branch's HLG, then ALWAYS invoke the ORIGINAL
  LLG Generator -> LLG Evaluator loop for the replacement before the next
  bottom-up iteration.

Only when every current branch is confirmed does global documentation coverage
run. Coverage receives the current HLG set and the confirmed reconstructed HLGs
as additional discovery signals. If documentation supports an autonomous
WHY-level intention not represented by any current HLG, coverage may request a
new HLG. Each added HLG is generated/evaluated, decomposed into evaluated LLGs,
and then re-enters the same bottom-up verification cycle.

``goal_update.py`` performs deterministic state mutation only. ``cycle_state.py``
performs convergence/repetition inspection only. There is one evolving current
HLG/LLG collection and no best-state rollback policy.
"""

